import fs from "node:fs/promises";
import { Workbook, SpreadsheetFile } from "@oai/artifact-tool";
const wb = Workbook.create();
const s = wb.worksheets.add("S");
s.getRange("A1:B5").values = [["Month","NAV"],["Jan",1],["Feb",1.1],["Mar",1.2],["Apr",1.3]];
s.getRange("D2").values = [[2]];
wb.names.add("ChartDates", "=OFFSET('S'!$A$2,0,0,'S'!$D$2,1)");
wb.names.add("ChartValues", "=OFFSET('S'!$B$2,0,0,'S'!$D$2,1)");
const c = s.charts.add("line", {title:"Test",from:{row:7,col:0},extent:{widthPx:600,heightPx:300}});
const series = c.series.add("NAV");
series.categoryFormula = "ChartDates";
series.formula = "ChartValues";
c.setPosition("A8:H20");
const before = await wb.render({sheetName:"S",range:"A1:H21",scale:1,format:"png"});
await fs.writeFile("dynamic_chart_before.png",new Uint8Array(await before.arrayBuffer()));
s.getRange("D2").values=[[4]];
wb.recalculate();
const after = await wb.render({sheetName:"S",range:"A1:H21",scale:1,format:"png"});
await fs.writeFile("dynamic_chart_after.png",new Uint8Array(await after.arrayBuffer()));
const out=await SpreadsheetFile.exportXlsx(wb); await out.save("dynamic_chart_test.xlsx");
console.log("series",series.formula,series.categoryFormula);
